-- The schema the Django backend left behind, restated so that a fresh database
-- gets exactly what an existing one already has.
--
-- **Every statement is IF NOT EXISTS, and that is the point of this file.** The
-- production database was built by Django's migrations 0001-0015 and already
-- holds every table below, with data in it. Flyway meets that database with no
-- history table, baselines it at version 0 (see `spring.flyway.baseline-*` in
-- application.yml), and then runs this file -- which finds everything already in
-- place and changes nothing. A fresh database, by contrast, is built from here.
--
-- Table and index names are Django's own (`myapp_*`, `auth_user`), kept rather
-- than tidied up so the two backends can be pointed at the same database: a
-- rollback to the Django image needs no data migration in either direction.
--
-- Foreign keys deliberately have no ON DELETE CASCADE. Django never put one on
-- the database -- it cascades in Python -- so the production constraints do not
-- have it either, and the code deletes children explicitly (see PostRepository)
-- to work against both.

-- The owner's login. Django's table, Django's columns, and Django's password
-- hash format (see DjangoPasswordEncoder), so an account created by
-- `manage.py createsuperuser` before the move still logs in after it.
CREATE TABLE IF NOT EXISTS auth_user (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password     varchar(128) NOT NULL,
    last_login   timestamptz  NULL,
    is_superuser boolean      NOT NULL,
    username     varchar(150) NOT NULL UNIQUE,
    first_name   varchar(150) NOT NULL,
    last_name    varchar(150) NOT NULL,
    email        varchar(254) NOT NULL,
    is_staff     boolean      NOT NULL,
    is_active    boolean      NOT NULL,
    date_joined  timestamptz  NOT NULL
);

CREATE TABLE IF NOT EXISTS myapp_post (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             varchar(200)  NOT NULL,
    slug              varchar(220)  NOT NULL UNIQUE,
    excerpt           text          NOT NULL,
    body              text          NOT NULL,
    status            varchar(20)   NOT NULL,
    published_at      timestamptz   NULL,
    created_at        timestamptz   NOT NULL,
    updated_at        timestamptz   NOT NULL,
    cover_image_alt   varchar(200)  NOT NULL,
    cover_image_url   varchar(500)  NOT NULL,
    view_count        integer       NOT NULL CHECK (view_count >= 0),
    tags              varchar(50)[] NOT NULL,
    comments_enabled  boolean       NOT NULL,
    reactions_enabled boolean       NOT NULL,
    theme             varchar(10)   NOT NULL
);
-- GIN, because browsing by tag is a containment test over an array.
CREATE INDEX IF NOT EXISTS myapp_post_tags_aa0585_gin ON myapp_post USING gin (tags);
CREATE INDEX IF NOT EXISTS myapp_post_status_5a87b3_idx ON myapp_post (status);

CREATE TABLE IF NOT EXISTS myapp_postviewday (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date    date    NOT NULL,
    count   integer NOT NULL CHECK (count >= 0),
    post_id bigint  NOT NULL REFERENCES myapp_post (id) DEFERRABLE INITIALLY DEFERRED,
    -- The identity of a row, and what lets recording a view be one upsert.
    CONSTRAINT unique_post_view_day UNIQUE (post_id, date)
);
CREATE INDEX IF NOT EXISTS myapp_postv_date_796716_idx ON myapp_postviewday (date);

CREATE TABLE IF NOT EXISTS myapp_book (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           varchar(200)  NOT NULL,
    slug            varchar(220)  NOT NULL UNIQUE,
    author          varchar(200)  NOT NULL,
    genres          varchar(50)[] NOT NULL,
    isbn            varchar(17)   NOT NULL,
    release_year    smallint      NULL CHECK (release_year >= 0),
    review          text          NOT NULL,
    cover_image_url varchar(500)  NOT NULL,
    cover_image_alt varchar(200)  NOT NULL,
    status          varchar(20)   NOT NULL,
    created_at      timestamptz   NOT NULL,
    updated_at      timestamptz   NOT NULL
);
CREATE INDEX IF NOT EXISTS myapp_book_genres_74040e_gin ON myapp_book USING gin (genres);
CREATE INDEX IF NOT EXISTS myapp_book_status_638abe_idx ON myapp_book (status);

CREATE TABLE IF NOT EXISTS myapp_comment (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_name varchar(80) NOT NULL,
    body        text        NOT NULL,
    status      varchar(20) NOT NULL,
    created_at  timestamptz NOT NULL,
    updated_at  timestamptz NOT NULL,
    post_id     bigint      NOT NULL REFERENCES myapp_post (id) DEFERRABLE INITIALLY DEFERRED
);
-- The one query the public page makes: this post's visible comments, in order.
CREATE INDEX IF NOT EXISTS myapp_comme_post_id_6797eb_idx ON myapp_comment (post_id, status, created_at);

CREATE TABLE IF NOT EXISTS myapp_reaction (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emoji      varchar(32) NOT NULL,
    visitor    varchar(64) NOT NULL,
    created_at timestamptz NOT NULL,
    post_id    bigint      NOT NULL REFERENCES myapp_post (id) DEFERRABLE INITIALLY DEFERRED,
    -- What makes the toggle a delete-or-insert rather than a read-then-write.
    CONSTRAINT unique_post_emoji_visitor UNIQUE (post_id, emoji, visitor)
);
CREATE INDEX IF NOT EXISTS myapp_react_post_id_a79821_idx ON myapp_reaction (post_id, emoji);

CREATE TABLE IF NOT EXISTS myapp_pagecontent (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key        varchar(32) NOT NULL UNIQUE,
    data       jsonb       NOT NULL,
    updated_at timestamptz NOT NULL
);
